/**
 * Drishti Script Exporter
 * Converts recorded AI browser telemetry actions into ready-to-run
 * Playwright (TypeScript/Python) and Puppeteer (JavaScript) automation scripts.
 */

export interface RecordedAction {
  action: string;
  payload?: Record<string, any>;
  url?: string;
  selector?: string;
  text?: string;
  key?: string;
  amount?: number;
  timestamp?: string;
}

export type ExportFormat = 'playwright-ts' | 'playwright-py' | 'puppeteer-js' | 'drishti-cli';

export function exportSessionScript(actions: (RecordedAction | string)[], format: ExportFormat): string {
  const parsed = actions.map((item) => {
    if (typeof item === 'string') {
      // Parse string action logs like "Completed MCP: NAVIGATE" or "CLICK: #submit"
      const parts = item.split(':');
      const action = parts[0].trim().toUpperCase().replace(/COMPLETED MCP\s*/, '').replace(/EXECUTING MCP\s*/, '');
      const detail = parts.slice(1).join(':').trim();
      return { action, detail };
    }
    return {
      action: item.action.toUpperCase(),
      detail: item.selector || item.text || item.url || JSON.stringify(item.payload || {}),
      ...item,
    };
  });

  switch (format) {
    case 'playwright-ts':
      return generatePlaywrightTS(parsed);
    case 'playwright-py':
      return generatePlaywrightPy(parsed);
    case 'puppeteer-js':
      return generatePuppeteerJS(parsed);
    case 'drishti-cli':
      return generateDrishtiCLI(parsed);
    default:
      return generatePlaywrightTS(parsed);
  }
}

function generatePlaywrightTS(actions: any[]): string {
  const lines: string[] = [
    `import { test, expect } from '@playwright/test';`,
    ``,
    `/**`,
    ` * Autonomous Mission Script`,
    ` * Generated by Drishti Browser AI (दृष्टि) v0.1.0 PRO`,
    ` */`,
    `test('Drishti Recorded Browser Mission', async ({ page }) => {`,
    `  // Configure viewport`,
    `  await page.setViewportSize({ width: 1280, height: 720 });`,
    ``,
  ];

  for (const a of actions) {
    const act = a.action;
    if (act.includes('NAVIGATE')) {
      const url = a.url || a.detail || 'https://example.com';
      lines.push(`  // Navigate`);
      lines.push(`  await page.goto('${url}', { waitUntil: 'domcontentloaded' });`);
    } else if (act.includes('CLICK')) {
      const sel = a.selector || a.detail || 'button';
      lines.push(`  // Click element`);
      lines.push(`  await page.locator('${escapeStr(sel)}').first().click();`);
    } else if (act.includes('TYPE')) {
      const sel = a.selector || 'input';
      const text = a.text || a.detail || '';
      lines.push(`  // Fill input text`);
      lines.push(`  await page.locator('${escapeStr(sel)}').first().fill('${escapeStr(text)}');`);
    } else if (act.includes('PRESS_KEY')) {
      const key = a.key || a.detail || 'Enter';
      lines.push(`  await page.keyboard.press('${escapeStr(key)}');`);
    } else if (act.includes('SCROLL')) {
      const amt = a.amount || 400;
      lines.push(`  await page.mouse.wheel(0, ${amt});`);
    } else if (act.includes('SCREENSHOT')) {
      lines.push(`  await page.screenshot({ path: 'drishti-step.png', fullPage: false });`);
    } else if (act.includes('WAIT')) {
      lines.push(`  await page.waitForTimeout(1000);`);
    }
  }

  lines.push(``);
  lines.push(`  // Verify execution complete`);
  lines.push(`  await expect(page).not.toHaveURL('about:blank');`);
  lines.push(`});`);
  return lines.join('\n');
}

function generatePlaywrightPy(actions: any[]): string {
  const lines: string[] = [
    `import asyncio`,
    `from playwright.async_api import async_playwright`,
    ``,
    `# Autonomous Mission Script`,
    `# Generated by Drishti Browser AI (दृष्टि) v0.1.0 PRO`,
    `async def main():`,
    `    async with async_playwright() as p:`,
    `        browser = await p.chromium.launch(headless=False)`,
    `        page = await browser.new_page()`,
    ``,
  ];

  for (const a of actions) {
    const act = a.action;
    if (act.includes('NAVIGATE')) {
      const url = a.url || a.detail || 'https://example.com';
      lines.push(`        await page.goto('${url}', wait_until='domcontentloaded')`);
    } else if (act.includes('CLICK')) {
      const sel = a.selector || a.detail || 'button';
      lines.push(`        await page.locator('${escapeStr(sel)}').first.click()`);
    } else if (act.includes('TYPE')) {
      const sel = a.selector || 'input';
      const text = a.text || a.detail || '';
      lines.push(`        await page.locator('${escapeStr(sel)}').first.fill('${escapeStr(text)}')`);
    } else if (act.includes('PRESS_KEY')) {
      const key = a.key || a.detail || 'Enter';
      lines.push(`        await page.keyboard.press('${escapeStr(key)}')`);
    } else if (act.includes('SCROLL')) {
      lines.push(`        await page.mouse.wheel(0, 400)`);
    }
  }

  lines.push(``);
  lines.push(`        await browser.close()`);
  lines.push(``);
  lines.push(`asyncio.run(main())`);
  return lines.join('\n');
}

function generatePuppeteerJS(actions: any[]): string {
  const lines: string[] = [
    `const puppeteer = require('puppeteer');`,
    ``,
    `/**`,
    ` * Autonomous Mission Script`,
    ` * Generated by Drishti Browser AI (दृष्टि) v0.1.0 PRO`,
    ` */`,
    `(async () => {`,
    `  const browser = await puppeteer.launch({ headless: false });`,
    `  const page = await browser.newPage();`,
    `  await page.setViewport({ width: 1280, height: 720 });`,
    ``,
  ];

  for (const a of actions) {
    const act = a.action;
    if (act.includes('NAVIGATE')) {
      const url = a.url || a.detail || 'https://example.com';
      lines.push(`  await page.goto('${url}', { waitUntil: 'networkidle2' });`);
    } else if (act.includes('CLICK')) {
      const sel = a.selector || a.detail || 'button';
      lines.push(`  await page.waitForSelector('${escapeStr(sel)}');`);
      lines.push(`  await page.click('${escapeStr(sel)}');`);
    } else if (act.includes('TYPE')) {
      const sel = a.selector || 'input';
      const text = a.text || a.detail || '';
      lines.push(`  await page.waitForSelector('${escapeStr(sel)}');`);
      lines.push(`  await page.type('${escapeStr(sel)}', '${escapeStr(text)}');`);
    } else if (act.includes('PRESS_KEY')) {
      const key = a.key || a.detail || 'Enter';
      lines.push(`  await page.keyboard.press('${escapeStr(key)}');`);
    } else if (act.includes('SCROLL')) {
      lines.push(`  await page.evaluate(() => window.scrollBy(0, 400));`);
    }
  }

  lines.push(``);
  lines.push(`  await browser.close();`);
  lines.push(`})();`);
  return lines.join('\n');
}

function generateDrishtiCLI(actions: any[]): string {
  const lines: string[] = [
    `# Drishti CLI Execution Steps`,
    `# Generated by Drishti Browser AI (दृष्टि) v0.1.0 PRO`,
    ``,
  ];

  for (const a of actions) {
    const act = a.action;
    if (act.includes('NAVIGATE')) {
      lines.push(`node scripts/drishti-exec.mjs navigate "${a.url || a.detail}"`);
    } else if (act.includes('CLICK')) {
      lines.push(`node scripts/drishti-exec.mjs click "${a.selector || a.detail}"`);
    } else if (act.includes('TYPE')) {
      lines.push(`node scripts/drishti-exec.mjs type "${a.selector || 'input'}" "${a.text || a.detail}"`);
    } else if (act.includes('SCROLL')) {
      lines.push(`node scripts/drishti-exec.mjs scroll "down" 400`);
    }
  }

  return lines.join('\n');
}

function escapeStr(s: string): string {
  return (s || '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}
